import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  arrowSchema,
  FIXED_STATISTICS_COLUMNS,
  SORT_COLUMNS,
  TABLE_COLUMNS,
  TABLES,
  type Table,
  TIME_COLUMN,
} from '../src/format/parquet/schema.js';

const OUT = new URL('../docs/format/schema.md', import.meta.url);

const TABLE_NOTES: Readonly<Record<Table, string>> = {
  spans: 'One row per span.',
  logs: 'One row per log record. Rows sort by `time_unix_nano`, falling back to `observed_time_unix_nano` when it is null.',
  points:
    'One row per metric data point, in long form: every point type shares the table, and the columns of the other types are null.',
  traces: 'One row per trace seen in the partition: a summary of its spans.',
  patterns:
    'Log pattern clusters (Drain) with their counts in the partition. See [Patterns](#patterns) for how rows combine.',
};

const esc = (s: string): string => s.replaceAll('|', '\\|');

function tableSection(table: Table): string {
  const types = new Map(arrowSchema(table).fields.map((f) => [f.name, String(f.type)]));
  const fixed = FIXED_STATISTICS_COLUMNS[table];
  const list = (names: readonly string[]): string =>
    names.length === 0 ? 'none' : names.map((c) => `\`${c}\``).join(', ');
  const rows = TABLE_COLUMNS[table].map(
    (c) =>
      `| \`${c.name}\` | ${esc(types.get(c.name) ?? '')} | ${c.type === 'json' ? 'JSON text' : c.type} | ${c.nullable ? 'yes' : 'no'} |`,
  );
  return [
    `## Table \`${table}\``,
    '',
    TABLE_NOTES[table],
    '',
    `- Sorted by: ${list(SORT_COLUMNS[table])}`,
    `- Time column (for the partition's \`timeMin\` and \`timeMax\`): \`${TIME_COLUMN[table]}\``,
    `- Fixed statistics columns: ${list(fixed)}`,
    '',
    '| column | Arrow type | logical type | nullable |',
    '|---|---|---|---|',
    ...rows,
  ].join('\n');
}

/** The text of `docs/format/schema.md`: the code's facts (columns, sort keys, statistics) plus short prose for the rest. */
export function renderSchemaDoc(): string {
  const parts = [
    `<!-- Generated by scripts/gen-schema-doc.ts from src/format/parquet/schema.ts (mise run gen). Do not edit by hand. -->

# Format 4 schema

Format 4 stores a report's data as Parquet files in numbered partitions (\`data/partitions/<p6>/<table>.parquet\`), listed
in the manifest. This page lists the tables and columns, the manifest, and how partitions combine. For the layout of the
report folder see the README's "Report layout and hosting".

Every table is written ZSTD-compressed, sorted by its sort columns (nulls last, stable). \`json\` columns hold JSON text
(attributes, events, bodies and the like) and are dictionary-encoded. OTLP \`uint32\` fields (flags, dropped counts) are
stored as \`int64\`. Times are absolute Unix nanoseconds as \`int64\`; the manifest writes them as decimal text.`,
    ...TABLES.map(tableSection),
    `## Points: delta columns and series identity

\`delta_value\`, \`delta_count\`, \`reset\` and \`out_of_order\` hold the normalized increase of a series since its
previous point. They are filled for delta-temporality sums (up-down counters included) and for histograms; other
point types leave them null. \`series_id\` is a 128-bit hash (hex text) of the series identity: the metric (name, type, unit,
temporality, monotonicity and, for an explicit histogram, its bounds), the resource, the scope and the point's attributes.
A series whose histogram bounds change is a new series.`,
    `## Patterns

- Cluster ids are unique within one Drain lineage.
- When a report compacts its own flush partitions, it sums patterns by \`cluster_id\`.
- When merge compacts copied partitions, it sums them by (\`cluster_id\`, \`template\`). So one compacted copy partition may
  hold the same \`cluster_id\` more than once.
- Readers combine patterns across partitions by template.`,
    `## Manifest (\`data/manifest.js\`)

The manifest is a script that registers its JSON payload. Its fields:

| field | meaning |
|---|---|
| \`formatVersion\` | \`4\` |
| \`otelHtmlVersion\` | the version of otel-html that wrote the report |
| \`title\` | the report title |
| \`epochUnixNano\` | decimal nanoseconds of the report's epoch |
| \`createdAt\`, \`updatedAt\` | ISO timestamps |
| \`complete\` | false while a writer holds the report open |
| \`range\` | \`{ start, end }\` as int64 nanosecond text, or null when the report holds no data |
| \`totals\` | row counts per signal: \`spans\`, \`logs\`, \`metrics\` |
| \`partitions\` | the partition list, see below |
| \`statisticsKeys\` | per table, the columns and \`attr:<key>\` / \`resource:<key>\` keys whose values are kept in each file's \`values\`; it includes the fixed statistics columns above |
| \`engine\` | \`{ format, version, assetsBase }\`: \`format\` is \`local\` or \`site\`, \`version\` the DuckDB engine version, \`assetsBase\` where the viewer and engine files load from |
| \`config\` | the viewer settings, dashboards and views |

Each \`partitions\` entry is \`{ n, source, files }\`. \`files\` has an entry per table the partition holds:
\`{ path, bytes, rows, timeMin, timeMax, values }\`, where \`values\` maps each statistics key to its distinct values in
the file, or to null when the file has more than the cap (or the table cannot answer the key).

### \`source\`

Where a partition came from:

- \`flush:<n>\`: the report's own flush partition number \`n\`.
- \`compact:<first>..<last>\`: the result of compacting partitions \`first\` to \`last\`.
- \`merge:<input>#<n>\`: a partition copied by merge. \`<input>\` is the input's index after the inputs are sorted by
  epoch, oldest first; \`<n>\` is the partition's number in that input.
- \`job:<id>\` and \`ci:<id>\`: also accepted by the manifest schema; the writer does not produce them yet.`,
  ];
  return `${parts.join('\n\n')}\n`;
}

if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  writeFileSync(OUT, renderSchemaDoc());
}
